@app.post("/filter-text", response_model=FilteredContent, tags=["필터링 기능"])
def filter_text_endpoint(request: PostContent):
    if text_filter is None:
        raise HTTPException(status_code=503, detail="필터 모델 준비 안됨")

    original_title = request.title
    original_content = request.content

    print("\n--- API 호출 ---")
    print(f"입력 원본 제목: '{original_title}'")
    print(f"입력 원본 내용:\n'{original_content}'")

    filtered_title = text_filter.mask_profanity(original_title)

    lines = original_content.split('\n')
    filtered_lines = []

    for line in lines:
        try:
            sentences = kss.split_sentences(line.strip())
        except:
            sentences = line.strip().split('.')

        safe_sentences = []
        for sentence in sentences:
            if not sentence.strip(): continue

            masked_sentence = text_filter.mask_profanity(sentence)
            if not text_filter.judge_by_intensity(masked_sentence):
                safe_sentences.append(masked_sentence)

        cleaned_line = " ".join(safe_sentences)

        if cleaned_line.strip():
            filtered_lines.append(cleaned_line)

    filtered_content_text = "<br>".join(filtered_lines)

    final_filtered_content = filtered_content_text

    print("\n--- 필터링 결과 ---")
    print(f"전달될 필터링 제목: '{filtered_title}'")
    print(f"전달될 필터링 내용:\n'{final_filtered_content}'")
    print("------------------")

    return {
        "filtered_title": filtered_title,
        "filtered_content": final_filtered_content,
    }

