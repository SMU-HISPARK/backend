# --- TextFilter 클래스 정의 (필터링 엔진) ---
class TextFilter:
    def __init__(self, model_path: str, bad_words_file: str):
        print("필터 시스템을 초기화합니다...")
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.tokenizer = AutoTokenizer.from_pretrained(model_path)
        self.model = BertForSequenceClassification.from_pretrained(model_path)
        self.model.to(self.device)
        self.model.eval()
        self.bad_words: Set[str] = self._load_bad_words(bad_words_file)
        print(f"필터 모델: {model_path}")
        print(f"욕설 단어: {len(self.bad_words):,} 개 로드됨")
        print("필터 초기화 완료.")

    def _load_bad_words(self, file_path: str) -> Set[str]:
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                return {line.strip() for line in f if line.strip()}
        except FileNotFoundError:
            print(f"WARNING: '{file_path}' 파일을 찾을 수 없습니다.")
            return set()

    def mask_profanity(self, text: str) -> str:
        masked_text = text
        for bad_word in self.bad_words:
            pattern = re.compile(re.escape(bad_word), re.IGNORECASE)
            def replacer(match):
                return '♡' * len(match.group(0))
            masked_text = pattern.sub(replacer, masked_text)
        return masked_text

    def judge_by_intensity(self, text: str, threshold: float = 1.8) -> bool:
        if not text.strip(): return False
        inputs = self.tokenizer(text, padding="max_length", truncation=True, max_length=256, return_tensors="pt").to(self.device)
        with torch.no_grad():
            logits = self.model(**inputs).logits
            intensity_score = logits.squeeze().item()
        print(f"문장: '{text}...' | AI 점수: {intensity_score:.4f}")
        return intensity_score >= threshold

